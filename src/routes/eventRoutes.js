import express from "express";
import { authenticate } from "../middleware/auth.js";
import * as c from "../controllers/eventController.js";
const router = express.Router();
router.use(authenticate);
router.get("/", c.listEvents);
router.post("/", c.createEvent);
router.get("/venues", c.listVenues);
router.post("/venues", c.createVenue);
router.put("/venues/:id", c.updateVenue);
router.delete("/venues/:id", c.deleteVenue);
router.get("/participants", c.listParticipants);
router.post("/participants", c.createParticipant);
router.put("/participants/:id", c.updateParticipant);
router.delete("/participants/:id", c.deleteParticipant);
router.get("/registrations", c.listRegistrations);
router.patch("/tickets/:id/check-in", c.checkInTicket);
router.patch("/registrations/:id/cancel", c.cancelRegistration);
router.get("/:id", c.getEvent);
router.put("/:id", c.updateEvent);
router.delete("/:id", c.deleteEvent);
router.get("/:id/schedule", c.listSchedule);
router.post("/:id/schedule", c.addScheduleItem);
router.put("/:id/schedule/:itemId", c.updateScheduleItem);
router.delete("/:id/schedule/:itemId", c.deleteScheduleItem);
router.get("/:id/ticket-types", c.listTicketTypes);
router.post("/:id/ticket-types", c.addTicketType);
router.put("/:id/ticket-types/:ticketTypeId", c.updateTicketType);
router.delete("/:id/ticket-types/:ticketTypeId", c.deleteTicketType);
router.post("/:id/registrations", c.registerParticipant);
export default router;
